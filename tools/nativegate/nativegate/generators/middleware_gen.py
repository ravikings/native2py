"""The generated service's middleware: request identity, access logs, auth, limits.

Emitted as one `middleware.py` per service with a single entry point,
`install_middleware(app, service_name)`, called by both the standalone
`service.py` and the composed gateway app. Same reason `error_gen` is shared:
middleware attaches to an *app*, and a service router mounted into a gateway
runs under the gateway's app, so installing it in one place only would miss
the deployment more likely to face the internet.

TWO RULES THIS FILE IS BUILT AROUND

**Secrets come from the environment, never from config or the image.** API
keys are read from `NATIVEGATE_API_KEYS` at startup. Nothing is baked into
`nativegate.yaml` (which is committed) or into a layer (which is pullable by
anyone who can reach the registry).

**Auth fails closed.** If `api.auth: api_key` is configured and no keys are
present in the environment, the service **refuses to start** rather than
serving unauthenticated. A misconfiguration that silently disables
authentication is worse than one that pages someone at deploy time — the
first is discovered by an attacker, the second by the person deploying.

WHAT IS DELIBERATELY HONEST ABOUT THE RATE LIMITER

It is per-process. Generated images run several gunicorn workers, so a limit
of N is really N×`WEB_CONCURRENCY` across the service, and it resets when a
worker is recycled. That is useful as a crude backstop against one client
melting one worker; it is **not** a quota system, and real global limiting
belongs at the ingress, where there is one place to count. Saying so is the
point — an in-process counter presented as a global limit is the kind of
control that is trusted until the day it matters.
"""

